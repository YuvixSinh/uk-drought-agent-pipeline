const listeners = new Set();

export function subscribe(fn) {
  listeners.add(fn);
  return () => listeners.delete(fn);
}

export function notify(reason = 'update') {
  for (const fn of listeners) {
    try {
      fn(state, reason);
    } catch (err) {
      console.error('State listener error:', err);
    }
  }
}

